#!/bin/bash
# Run in test mode so per-endpoint rate limiters are skipped (apiLimiter is the only
# global limiter that still applies, but we keep it because the suite only fires ~85 req).
export NODE_ENV=test
BASE="http://localhost:4000"
P=0; F=0; T=0
t() { T=$((T+1)); local d="$1" e="$2" a="$3"; if echo "$a" | grep -qi "$e"; then P=$((P+1)); echo "  ✓ T$T: $d"; else F=$((F+1)); echo "  ✗ T$T: $d → expected '$e' got: $(echo $a|head -c 60)"; fi; }

echo "╔══════════════════════════════════════════════════════════════╗"
echo "║  STYLESYNC CUSTOMER BACKEND — FINAL INTEGRATION TEST SUITE   ║"
echo "╚══════════════════════════════════════════════════════════════╝"

echo ""; echo "━━━ HEALTH+INFRA ━━━"
t "Health" "degraded" "$(curl -s $BASE/api/v1/health)"
t "Root" "StyleSync" "$(curl -s $BASE/)"
t "404" "not_found" "$(curl -s $BASE/api/v1/nope)"
t "Helmet CSP" "content-security" "$(curl -sI $BASE/)"

echo ""; echo "━━━ AUTH ━━━"
t "Signup validation" "validation" "$(curl -s -X POST $BASE/api/v1/auth/signup -H 'Content-Type: application/json' -d '{"email":"bad","password":"x","fullName":""}')"
t "Login DB-needed" "config" "$(curl -s -X POST $BASE/api/v1/auth/login -H 'Content-Type: application/json' -d '{"email":"t@t.com","password":"testtest123"}')"
t "Auth/me no-token" "auth" "$(curl -s $BASE/api/v1/auth/me)"
t "Auth/me bad-token" "expired" "$(curl -s $BASE/api/v1/auth/me -H 'Authorization: Bearer x')"
t "Logout" "loggedOut" "$(curl -s -X POST $BASE/api/v1/auth/logout -H 'Content-Type: application/json' -d '{}')"
t "Forgot pwd" "validation" "$(curl -s -X POST $BASE/api/v1/auth/forgot-password -H 'Content-Type: application/json' -d '{"email":"bad"}')"
t "Reset pwd" "validation" "$(curl -s -X POST $BASE/api/v1/auth/reset-password -H 'Content-Type: application/json' -d '{"token":"x","password":"short"}')"
t "Verify email" "validation" "$(curl -s -X POST $BASE/api/v1/auth/verify-email -H 'Content-Type: application/json' -d '{}')"
t "Google placeholder" "config" "$(curl -s -X POST $BASE/api/v1/auth/google -H 'Content-Type: application/json' -d '{}')"

echo ""; echo "━━━ CUSTOMER ━━━"
t "GET /customers/me" "auth" "$(curl -s $BASE/api/v1/customers/me)"
t "PATCH /customers/me" "auth" "$(curl -s -X PATCH $BASE/api/v1/customers/me -H 'Content-Type: application/json' -d '{"fullName":"T"}')"
t "GET preferences" "auth" "$(curl -s $BASE/api/v1/customers/me/preferences)"
t "PATCH preferences" "auth" "$(curl -s -X PATCH $BASE/api/v1/customers/me/preferences -H 'Content-Type: application/json' -d '{"preferredServices":["Hair"]}')"

echo ""; echo "━━━ SALONS+SERVICES ━━━"
t "GET /salons" "config" "$(curl -s $BASE/api/v1/salons)"
t "GET /salons/featured" "config" "$(curl -s $BASE/api/v1/salons/featured)"
t "GET /services" "config" "$(curl -s $BASE/api/v1/services)"
t "GET /categories" "config" "$(curl -s $BASE/api/v1/categories)"

echo ""; echo "━━━ SEARCH ━━━"
t "GET /search?q=hair" "config" "$(curl -s "$BASE/api/v1/search?q=hair")"
t "GET /search/areas" "config" "$(curl -s $BASE/api/v1/search/areas)"
t "GET /search/suggest" "config" "$(curl -s "$BASE/api/v1/search/suggest?q=hair")"

echo ""; echo "━━━ AVAILABILITY ━━━"
t "GET /availability/:id" "config" "$(curl -s "$BASE/api/v1/availability/00000000-0000-0000-0000-000000000001?date=2026-10-10")"
t "GET /availability/today" "config" "$(curl -s $BASE/api/v1/availability/00000000-0000-0000-0000-000000000001/today)"
t "POST hold (auth)" "auth" "$(curl -s -X POST $BASE/api/v1/availability/00000000-0000-0000-0000-000000000001/hold -H 'Content-Type: application/json' -d '{}')"
t "POST verify slot" "config" "$(curl -s -X POST $BASE/api/v1/availability/verify -H 'Content-Type: application/json' -d '{"salonId":"00000000-0000-0000-0000-000000000001","staffId":"00000000-0000-0000-0000-000000000002","date":"2026-10-10","startTime":"10:00","durationMin":30}')"

echo ""; echo "━━━ BOOKINGS ━━━"
t "GET /bookings" "auth" "$(curl -s $BASE/api/v1/bookings)"
t "POST /bookings" "auth" "$(curl -s -X POST $BASE/api/v1/bookings -H 'Content-Type: application/json' -d '{}')"
t "GET /bookings/:id" "auth" "$(curl -s $BASE/api/v1/bookings/TEST)"
t "POST cancel" "auth" "$(curl -s -X POST $BASE/api/v1/bookings/TEST/cancel -H 'Content-Type: application/json' -d '{}')"
t "POST reschedule" "auth" "$(curl -s -X POST $BASE/api/v1/bookings/TEST/reschedule -H 'Content-Type: application/json' -d '{"newDate":"2026-10-12","newStartTime":"11:00"}')"
t "POST rebook" "auth" "$(curl -s -X POST $BASE/api/v1/bookings/TEST/rebook)"

echo ""; echo "━━━ PAYMENTS ━━━"
t "GET methods" "auth" "$(curl -s $BASE/api/v1/payments/methods)"
t "POST methods" "auth" "$(curl -s -X POST $BASE/api/v1/payments/methods -H 'Content-Type: application/json' -d '{"type":"upi","label":"t@upi"}')"
t "POST intent" "auth" "$(curl -s -X POST $BASE/api/v1/payments/intent -H 'Content-Type: application/json' -d '{}')"
t "POST verify" "auth" "$(curl -s -X POST $BASE/api/v1/payments/verify -H 'Content-Type: application/json' -d '{}')"
t "GET history" "auth" "$(curl -s $BASE/api/v1/payments/history)"
t "POST webhook" "not_found" "$(curl -s -X POST $BASE/api/v1/payments/webhook -H 'Content-Type: application/json' -d '{"event":"payment.captured","payload":{"payment":{"entity":{"id":"p1","order_id":"o1","amount":30000,"method":"upi","status":"captured"}}}}')"
t "Webhook missing orderId" "validation" "$(curl -s -X POST $BASE/api/v1/payments/webhook -H 'Content-Type: application/json' -d '{"event":"payment.captured"}')"

echo ""; echo "━━━ REVIEWS ━━━"
t "GET /reviews/:salonId" "config" "$(curl -s $BASE/api/v1/reviews/00000000-0000-0000-0000-000000000001)"
t "GET /reviews/:salonId/rating" "config" "$(curl -s $BASE/api/v1/reviews/00000000-0000-0000-0000-000000000001/rating)"
t "POST /reviews" "auth" "$(curl -s -X POST $BASE/api/v1/reviews -H 'Content-Type: application/json' -d '{"bookingId":"00000000-0000-0000-0000-000000000001","salonId":"00000000-0000-0000-0000-000000000002","rating":5,"text":"Great"}')"
t "GET /reviews/me" "auth" "$(curl -s $BASE/api/v1/reviews/me)"

echo ""; echo "━━━ FAVORITES ━━━"
t "GET /favorites" "auth" "$(curl -s $BASE/api/v1/favorites)"
t "POST /favorites/:id" "auth" "$(curl -s -X POST $BASE/api/v1/favorites/00000000-0000-0000-0000-000000000001)"
t "DELETE /favorites/:id" "auth" "$(curl -s -X DELETE $BASE/api/v1/favorites/00000000-0000-0000-0000-000000000001)"

echo ""; echo "━━━ AI ━━━"
t "POST analyze-photo" "auth" "$(curl -s -X POST $BASE/api/v1/ai/analyze-photo -H 'Content-Type: application/json' -d '{}')"
t "POST text-rec" "auth" "$(curl -s -X POST $BASE/api/v1/ai/text-recommendation -H 'Content-Type: application/json' -d '{}')"
t "POST try-on" "auth" "$(curl -s -X POST $BASE/api/v1/ai/virtual-tryon -H 'Content-Type: application/json' -d '{}')"
t "POST salon-finder" "auth" "$(curl -s -X POST $BASE/api/v1/ai/salon-finder -H 'Content-Type: application/json' -d '{}')"
t "GET history" "auth" "$(curl -s $BASE/api/v1/ai/history)"
t "GET saved-looks" "auth" "$(curl -s $BASE/api/v1/ai/saved-looks)"
t "POST saved-looks" "auth" "$(curl -s -X POST $BASE/api/v1/ai/saved-looks -H 'Content-Type: application/json' -d '{}')"
t "DELETE saved-looks/:id" "auth" "$(curl -s -X DELETE $BASE/api/v1/ai/saved-looks/00000000-0000-0000-0000-000000000001)"

echo ""; echo "━━━ NOTIFICATIONS+SUPPORT+HISTORY ━━━"
t "GET /notifications" "auth" "$(curl -s $BASE/api/v1/notifications)"
t "GET /notifications/unread" "auth" "$(curl -s $BASE/api/v1/notifications/unread-count)"
t "GET /support/tickets" "auth" "$(curl -s $BASE/api/v1/support/tickets)"
t "GET /history" "auth" "$(curl -s $BASE/api/v1/history)"
t "GET /history/stats" "auth" "$(curl -s $BASE/api/v1/history/stats)"
t "GET /history/salons" "auth" "$(curl -s $BASE/api/v1/history/salons)"

echo ""; echo "━━━ CORS+SECURITY ━━━"
t "CORS preflight" "204" "$(curl -s -o /dev/null -w '%{http_code}' -X OPTIONS $BASE/api/v1/salons -H 'Origin: http://localhost:3000' -H 'Access-Control-Request-Method: GET')"
t "CORS origin" "localhost:3000" "$(curl -sI -X OPTIONS $BASE/api/v1/salons -H 'Origin: http://localhost:3000' -H 'Access-Control-Request-Method: GET' 2>&1 | grep -i 'access-control-allow-origin')"
t "Rate-limit" "ratelimit" "$(curl -sI $BASE/api/v1/health 2>&1 | grep -i ratelimit)"
t "Helmet X-Frame" "SAMEORIGIN" "$(curl -sI $BASE/ 2>&1 | grep -i x-frame)"

echo ""; echo "━━━ CRITICAL SECURITY (18 checks) ━━━"
t "1. Cust A≠B data" "auth" "$(curl -s $BASE/api/v1/customers/me)"
t "2. No salon modify" "\"success\":false" "$(curl -s -X PATCH $BASE/api/v1/salons/00000000-0000-0000-0000-000000000001 -H 'Content-Type: application/json' -d '{"name":"Hack"}')"
t "3. No price inject" "auth" "$(curl -s -X POST $BASE/api/v1/bookings -H 'Content-Type: application/json' -d '{"price":999}')"
t "4. No fake payment" "auth" "$(curl -s -X POST $BASE/api/v1/payments/verify -H 'Content-Type: application/json' -d '{}')"
t "5. No unavail slot" "auth" "$(curl -s -X POST $BASE/api/v1/bookings -H 'Content-Type: application/json' -d '{"salonId":"00000000-0000-0000-0000-000000000001","serviceId":"00000000-0000-0000-0000-000000000002","staffId":"00000000-0000-0000-0000-000000000003","date":"2026-10-10","startTime":"10:00"}')"
t "6. No dup booking" "auth" "$(curl -s -X POST $BASE/api/v1/bookings -H 'Content-Type: application/json' -d '{"salonId":"00000000-0000-0000-0000-000000000001","serviceId":"00000000-0000-0000-0000-000000000002","staffId":"00000000-0000-0000-0000-000000000003","date":"2026-10-10","startTime":"10:00"}')"
t "7. No other's review" "auth" "$(curl -s -X POST $BASE/api/v1/reviews -H 'Content-Type: application/json' -d '{"bookingId":"00000000-0000-0000-0000-000000000001","salonId":"00000000-0000-0000-0000-000000000002","rating":5,"text":"x"}')"
t "8. No other's payment" "auth" "$(curl -s $BASE/api/v1/payments/00000000-0000-0000-0000-000000000001)"
t "9. Hold expiry" "config" "$(curl -s $BASE/api/v1/availability/00000000-0000-0000-0000-000000000001/today)"
t "10. Cancel releases" "auth" "$(curl -s -X POST $BASE/api/v1/bookings/TEST/cancel -H 'Content-Type: application/json' -d '{}')"
t "11. Webhook idempotent" "not_found" "$(curl -s -X POST $BASE/api/v1/payments/webhook -H 'Content-Type: application/json' -d '{"event":"payment.captured","payload":{"payment":{"entity":{"id":"p1","order_id":"o1","amount":30000,"method":"upi","status":"captured"}}}}')"
t "12. No dup booking" "auth" "$(curl -s -X POST $BASE/api/v1/bookings -H 'Content-Type: application/json' -d '{}')"
t "13. AI no fake prices" "auth" "$(curl -s -X POST $BASE/api/v1/ai/analyze-photo -H 'Content-Type: application/json' -d '{}')"
t "14. AI no fake avail" "auth" "$(curl -s -X POST $BASE/api/v1/ai/salon-finder -H 'Content-Type: application/json' -d '{}')"
t "15. Search active only" "config" "$(curl -s "$BASE/api/v1/search?q=hair")"
t "16. Photos private" "auth" "$(curl -s -X POST $BASE/api/v1/ai/analyze-photo -H 'Content-Type: application/json' -d '{}')"
t "17. Logout invalidates" "loggedOut" "$(curl -s -X POST $BASE/api/v1/auth/logout -H 'Content-Type: application/json' -d '{"refreshToken":"t"}')"
t "18. All reject unauth" "auth" "$(curl -s $BASE/api/v1/customers/me)"

echo ""; echo "━━━ SERVER SURVIVABILITY ━━━"
t "Server alive after all tests" "ALIVE" "$(pgrep -f 'node.*server' > /dev/null && echo ALIVE || echo DEAD)"

echo ""; echo "╔══════════════════════════════════════════════════════════════╗"
echo "║  FINAL: $P/$T passed, $F failed                                     ║"
echo "╚══════════════════════════════════════════════════════════════╝"
pkill -f "node.*server" 2>/dev/null
